function signal(
  ev: Evidence[],
  id: ID,
  type: SignalType,
  evidenceId: ID,
  headline: string,
  strength: Signal["strength"],
  implication: string,
): Signal {
  const e = ev.find((x) => x.id === evidenceId);
  if (!e?.publishedAt) throw new Error(`Sample signal ${id} needs dated evidence ${evidenceId}`);
  return { id, type, headline, date: e.publishedAt, url: e.url, host: e.host, evidenceId, strength, usableInOutreach: type !== "sensitive", implication };
}

type Met = "true" | "false" | "unknown";
function met(usage: Met, size: Met, warehouse: Met, funded: Met, finance: Met, pricingChange: Met, notes: Partial<Record<string, string>> = {}): Account["criteria"] {
  const rows: [string, Met][] = [
    [CRITERION.usage, usage],
    [CRITERION.size, size],
    [CRITERION.warehouse, warehouse],
    [CRITERION.funded, funded],
    [CRITERION.finance, finance],
    [CRITERION.pricingChange, pricingChange],
  ];
  return rows.map(([criterionId, m]) => ({ criterionId, met: m, ...(notes[criterionId] ? { note: notes[criterionId] } : {}) }));
}

function enrichment(
  c: Clock,
  e: Partial<Enrichment> & { roles: [string, number, string[]][]; news?: Enrichment["news"] },
): Enrichment {
  const { roles, ...rest } = e;
  return {
    crawledAt: c.at(-1, "07:58"),
    tech: [],
    socials: {},
    openRoles: roles.reduce((n, r) => n + r[1], 0),
    rolesByTeam: roles.map(([team, count, titles]) => ({ team, count, titles })),
    news: [],
    ...rest,
  };
}

